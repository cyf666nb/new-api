import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const projectDir = dirname(scriptDir)
const repoDir = dirname(dirname(projectDir))
const demoDir = join(repoDir, 'demo')
const outputPath = join(projectDir, 'src', 'generated', 'pages.ts')

const htmlFiles = readdirSync(demoDir).filter((name) => name.endsWith('.html')).sort()

const pages = htmlFiles.map((file) => {
  const source = readFileSync(join(demoDir, file), 'utf8')
  const title = source.match(/<title>(.*?)<\/title>/s)?.[1]?.trim() ?? file
  const body = source.match(/<body[^>]*>([\s\S]*?)<\/body>/i)?.[1] ?? ''
  const inlineStyles = Array.from(source.matchAll(/<style[^>]*>[\s\S]*?<\/style>/gi), (match) => match[0]).join('\n')

  const scripts = []
  const externalScripts = []
  for (const match of source.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attrs = match[1] ?? ''
    const scriptBody = match[2] ?? ''
    const src = attrs.match(/src=["']([^"']+)["']/i)?.[1]

    if (src) {
      if (!src.includes('cdn.tailwindcss.com')) {
        externalScripts.push(src)
      }
      continue
    }

    if (!scriptBody.includes('tailwind.config')) {
      scripts.push(scriptBody.trim())
    }
  }

  const bodyHtml = body.replace(/<script[^>]*>[\s\S]*?<\/script>/gi, '').trim()
  const html = [inlineStyles, bodyHtml].filter(Boolean).join('\n')

  return {
    id: file.replace(/\.html$/, ''),
    file,
    title,
    html,
    externalScripts,
    scripts,
  }
})

const ids = pages.map((page) => JSON.stringify(page.id)).join(' | ')
const body = `// Generated by scripts/generate-demo-pages.mjs. Do not edit by hand.
export type DemoPageId = ${ids}

export interface DemoPageDefinition {
  file: string
  title: string
  html: string
  externalScripts: string[]
  scripts: string[]
}

export const demoPages = ${JSON.stringify(
  Object.fromEntries(
    pages.map(({ id, ...definition }) => [id, definition]),
  ),
  null,
  2,
)} as const satisfies Record<DemoPageId, DemoPageDefinition>
`

writeFileSync(outputPath, body)
console.log(`Generated ${pages.length} demo pages at ${outputPath}`)
